import Foundation

var checks = 0
@MainActor func expect(_ condition: @autoclosure () -> Bool, _ name: String) {
    checks += 1
    precondition(condition(), name)
}
typealias State = FacilitySearchLifecycle
var state = State()
expect(!state.active && !state.blocking, "initial state does not spin")
state.begin(generation: 1)
expect(state.blocking && state.pending.count == 2, "new search waits for two providers")
expect(state.showResults(generation: 1), "first usable result accepted")
expect(!state.blocking && state.active, "usable results stop blocking without hiding remaining source")
expect(state.receive(.appleMaps, succeeded: true, hasResults: true, generation: 1), "first source completes")
expect(!state.complete, "other source may still complete quietly")
expect(state.receive(.openStreetMap, succeeded: false, hasResults: false, generation: 1), "failure recorded separately")
expect(state.finish(generation: 1) == .partialResults, "a failed source cannot discard valid places")
expect(!state.active && !state.blocking, "completion always clears spinner")
expect(!state.receive(.openStreetMap, succeeded: true, hasResults: true, generation: 1), "late callback after finish ignored")

state.begin(generation: 2)
_ = state.receive(.appleMaps, succeeded: true, hasResults: false, generation: 2)
_ = state.receive(.openStreetMap, succeeded: true, hasResults: false, generation: 2)
expect(state.finish(generation: 2) == .empty, "valid empty results are not network errors")
state.begin(generation: 3)
_ = state.receive(.appleMaps, succeeded: true, hasResults: false, generation: 3)
_ = state.receive(.openStreetMap, succeeded: false, hasResults: false, generation: 3)
expect(state.finish(generation: 3) == .partialEmpty, "partial empty is neither confirmed absence nor total failure")
state.begin(generation: 4)
expect(state.finish(generation: 4) == .unavailable, "deadline ends a provider that never calls back")
expect(!state.blocking, "hung sources cannot retain the spinner")
state.begin(generation: 5)
_ = state.showResults(generation: 5)
expect(state.finish(generation: 5) == .partialResults, "deadline preserves streamed results")
state.begin(generation: 6)
state.cancel()
expect(!state.active && !state.blocking, "navigation cancellation ends loading immediately")
expect(!state.showResults(generation: 6), "cancelled result cannot revive the page")
expect(state.finish(generation: 6) == nil, "cancelled deadline cannot overwrite page state")
state.begin(generation: 7)
state.begin(generation: 8)
expect(!state.receive(.appleMaps, succeeded: true, hasResults: true, generation: 7), "previous sport response rejected")
expect(!state.showResults(generation: 7), "previous sport partial batch rejected")
expect(state.finish(generation: 7) == nil, "previous deadline cannot stop new sport")
expect(state.blocking && state.pending.count == 2, "new sport still owns loading")
_ = state.receive(.openStreetMap, succeeded: true, hasResults: true, generation: 8)
expect(!state.receive(.openStreetMap, succeeded: true, hasResults: true, generation: 8), "duplicate callbacks do not complete another source")
_ = state.receive(.appleMaps, succeeded: true, hasResults: false, generation: 8)
expect(state.finish(generation: 8) == .results, "successful source with results and a valid empty source is success")
expect(state.finish(generation: 8) == nil, "terminal completion is idempotent")
print("MAP_LIFECYCLE_PASS checks=\(checks) swift6=true")
